namespace optiling {
const uint32_t BLOCK_DIM = 32;
static ge::graphStatus TilingFunc(gert::TilingContext* context)
{
    ShufflenetUnitCustomTilingData tiling;
    const gert::Shape* input_shape = context->GetInputShape(0);
    const std::vector<int64_t>& input_dims = input_shape->GetOriginShape().GetDims();
    uint32_t batchSize = static_cast<uint32_t>(input_dims[0]);
    uint32_t inChannels = static_cast<uint32_t>(input_dims[1]);
    uint32_t height = static_cast<uint32_t>(input_dims[2]);
    uint32_t width = static_cast<uint32_t>(input_dims[3]);
    uint32_t outChannels = static_cast<uint32_t>(context->GetOutputShape(0)->GetOriginShape().GetDims()[1]);
    uint32_t groups = 3;
    uint32_t midChannels = outChannels / 4;
    
    context->SetBlockDim(BLOCK_DIM);
    tiling.set_batchSize(batchSize);
    tiling.set_inChannels(inChannels);
    tiling.set_outChannels(outChannels);
    tiling.set_height(height);
    tiling.set_width(width);
    tiling.set_groups(groups);
    tiling.set_midChannels(midChannels);
    tiling.set_conv1WeightSize(inChannels * midChannels * 1 * 1);
    tiling.set_conv2WeightSize(midChannels * midChannels * 3 * 3);
    tiling.set_conv3WeightSize(midChannels * outChannels * 1 * 1);
    tiling.set_shortcutConvWeightSize(inChannels * outChannels * 1 * 1);
    tiling.SaveToBuffer(context->GetRawTilingData()->GetData(), context->GetRawTilingData()->GetCapacity());
    context->GetRawTilingData()->SetDataSize(tiling.GetDataSize());
    size_t *currentWorkspace = context->GetWorkspaceSizes(1);
    currentWorkspace[0] = 0;
    return ge::GRAPH_SUCCESS;
}
}

namespace ge {
static ge::graphStatus InferShape(gert::InferShapeContext* context)
{
    const gert::Shape* x1_shape = context->GetInputShape(0);
    gert::Shape* y_shape = context->GetOutputShape(0);
    *y_shape = *x1_shape;
    return GRAPH_SUCCESS;
}
static ge::graphStatus InferDataType(gert::InferDataTypeContext *context)
{
const auto inputDataType = context->GetInputDataType(0);
context->SetOutputDataType(0, inputDataType);
return ge::GRAPH_SUCCESS;
}
}

